#[test]
fn bound_displacement_sofia() {
    DebugSession::init(LogLevel::Info, Backtrace::Short);
    let dbg = Dbg::new("test model_cached", "bound_displacement_sofia");
    log::debug!("\n{}", dbg);
    let test_duration = TestDuration::new(&dbg, Duration::from_secs(3000));
    test_duration.run().unwrap();
    let cache_dir: PathBuf = "src/algorithm/entities/model_cached/test/sofia".into();
    let model_dir: PathBuf = "src/assets/model/sofia".into();
    let model_center_coord = Position::new(65.250, 0., 0.);
    let bounds = Bounds::from_array(&PHYSICAL_FRAMES, model_center_coord.x()).unwrap();
    let thread_pool = ThreadPool::new(&dbg, Some(30));
    let delta_pos = Some(model_center_coord.clone());
    let mut displacement_shape = DisplacementShape::new_uninit(
        &dbg,
        model_dir.clone().join(PathBuf::from("hull.stl")),
        delta_pos,
        1000.,
    );
    displacement_shape.init().unwrap();
    let mut bound_displacement = BoundDisplacementCache::new(
        &dbg,
        Arc::new(RwLock::new(displacement_shape)),
        cache_dir.clone().join("disp_bounded"),
        0.01,
        bounds.clone(),
        thread_pool.scheduler().clone(),
    );
    bound_displacement.init().unwrap();// rebuild().unwrap();

    let (epsilon_p, epsilon_abs) = (0.1, 0.1);

    for (i, (r, t)) in bound_displacement
        .get(6., 0.1)
        .unwrap()
        .iter()
        .zip(TARGET_6000_01.iter())
        .enumerate()
    {
        let delta = (r - t).abs();
        assert!(
            delta < epsilon_p * (r.abs().max(t.abs())) || delta < epsilon_abs,
            "\n i:{}, result: {r}\ntarget: {t}", i as i32 - 5
        );
    }
    for (r, t) in bound_displacement
        .get(4., 1.)
        .unwrap()
        .iter()
        .zip(TARGET_4000_1.iter())
    {
        let delta = (r - t).abs();
        assert!(
            delta < epsilon_p * (r.abs().max(t.abs())) || delta < epsilon_abs,
            "\nresult: {r}\ntarget: {t}"
        );
    }
    for (r, t) in bound_displacement
        .get(3.5, 5.)
        .unwrap()
        .iter()
        .zip(TARGET_3500_5.iter())
    {
        let delta = (r - t).abs();
        assert!(
            delta < epsilon_p * (r.abs().max(t.abs())) || delta < epsilon_abs,
            "\nresult: {r}\ntarget: {t}"
        );
    }
    test_duration.exit();
}
